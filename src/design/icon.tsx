export type IconName = keyof typeof ICONS;

/** Rows, buttons and menus; toolbars and the sidebar; phones and empty states. */
export type IconSize = 16 | 20 | 24;

const STROKE: Record<IconSize, number> = { 16: 1.75, 20: 1.75, 24: 1.5 };

export type IconTone = Extract<
  ColorName,
  "fg" | "muted" | "subtle" | "accent" | "on-accent" | "success" | "warning" | "danger" | "info"
>;

export interface IconProps {
  name: IconName;
  size?: IconSize;
  tone?: IconTone;
  /** A colour from `useThemeColors()`, when the tone depends on the surface. */
  color?: string;
}

/** An icon a build doesn't know (a bot's widget may name one) draws nothing. */
export function Icon({ name, size = 16, tone = "muted", color }: IconProps) {
  const colors = useThemeColors();
  const Glyph = ICONS[name] as LucideIcon | undefined;
  if (!Glyph) return null;
  return <Glyph size={size} strokeWidth={STROKE[size]} color={color ?? colors[tone]} />;
}
