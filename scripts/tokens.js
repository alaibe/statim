#!/usr/bin/env node
// Writes src/design/laibe/tokens.json and src/global.css from the design system's tokens.css (copied byte for byte).
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const SOURCE = path.join(ROOT, "src/design/laibe/tokens.css");
const JSON_OUT = path.join(ROOT, "src/design/laibe/tokens.json");
const CSS_OUT = path.join(ROOT, "src/global.css");

const ACCENT = "ultraviolet";

const COLORS = [
  "void",
  "side",
  "bg",
  "panel",
  "hover",
  "selection",
  "line",
  "line-strong",
  "subtle",
  "muted",
  "fg",
  "accent",
  "accent-strong",
  "accent-soft",
  "on-accent",
  "danger",
  "warning",
  "success",
  "info",
];

function block(css, selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`tokens.css has no ${selector} block`);
  return css.slice(start, css.indexOf("}", start));
}

function declarations(text) {
  const found = {};
  for (const [, name, value] of text.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)) found[name] = value.trim();
  return found;
}

function px(value) {
  const match = /^(-?[\d.]+)(px|ms)?$/.exec(value);
  if (!match) throw new Error(`not a size: ${value}`);
  return Number(match[1]);
}

function em(value) {
  return value === "0" ? 0 : Number(value.replace(/em$/, ""));
}

function bezier(value) {
  const match = /^cubic-bezier\(([^)]+)\)$/.exec(value);
  if (!match) throw new Error(`not an easing: ${value}`);
  return match[1].split(",").map((n) => Number(n.trim()));
}

function lightDark(value) {
  const match = /^light-dark\((#[0-9a-f]{6}),\s*(#[0-9a-f]{6})\)$/i.exec(value);
  if (!match) throw new Error(`not light-dark(): ${value}`);
  return { light: match[1].toLowerCase(), dark: match[2].toLowerCase() };
}

function group(all, prefix, convert) {
  return Object.fromEntries(
    Object.entries(all)
      .filter(([name]) => name.startsWith(`${prefix}-`))
      .map(([name, value]) => [name.slice(prefix.length + 1), convert(value)]),
  );
}

function generate(css) {
  const root = declarations(block(css, ":root"));
  const accent = declarations(block(css, `[data-accent="${ACCENT}"]`));
  const all = { ...root, ...accent };

  const colors = Object.fromEntries(
    COLORS.map((name) => {
      if (!all[name]) throw new Error(`tokens.css has no --${name}`);
      return [name, lightDark(all[name])];
    }),
  );

  const tokens = {
    accent: ACCENT,
    colors,
    fontSize: group(root, "text", px),
    leading: group(root, "leading", Number),
    tracking: group(root, "tracking", em),
    space: group(root, "space", px),
    radius: group(root, "radius", px),
    chamfer: group(root, "chamfer", px),
    control: group(root, "control", px),
    layout: group(root, "layout", px),
    size: group(root, "size", px),
    layer: group(root, "layer", Number),
    duration: group(root, "duration", px),
    ease: group(root, "ease", bezier),
    shadow: group(root, "shadow", String),
  };
  return { json: `${JSON.stringify(tokens, null, 2)}\n`, css: globalCss(colors) };
}

function channels(hex) {
  return [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16)).join(" ");
}

function variables(colors, mode) {
  return Object.entries(colors)
    .map(([name, value]) => `    --color-${name}: ${channels(value[mode])};`)
    .join("\n");
}

function globalCss(colors) {
  return `@tailwind base;
@tailwind components;
@tailwind utilities;

/* Generated by scripts/tokens.js from src/design/laibe/tokens.css (${ACCENT} accent): run \`npm run tokens\`. */
@layer base {
  :root {
${variables(colors, "light")}
  }

  .dark:root {
${variables(colors, "dark")}
  }

  /* Keyboard focus draws --focus-ring on everything focusable; a mouse focus draws nothing. */
  input,
  textarea,
  :focus:not(:focus-visible) {
    outline: none;
  }
  :focus-visible {
    outline: none;
    box-shadow:
      0 0 0 2px rgb(var(--color-bg)),
      0 0 0 3px rgb(var(--color-accent)),
      0 0 14px rgb(var(--color-accent) / 0.45) !important;
  }
  /* An input inside a control that draws the ring around itself. */
  [data-bare]:focus-visible {
    box-shadow: none !important;
  }
  ::selection {
    background-color: rgb(var(--color-selection));
  }
}
`;
}

module.exports = { generate, SOURCE, JSON_OUT, CSS_OUT };

if (require.main === module) {
  const { json, css } = generate(fs.readFileSync(SOURCE, "utf8"));
  fs.writeFileSync(JSON_OUT, json);
  fs.writeFileSync(CSS_OUT, css);
}
